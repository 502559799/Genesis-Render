#!/usr/bin/env python3
# Genesis Render - compile GLSL shaders to SPIR-V and embed both the SPIR-V
# blobs and the original GLSL sources (used by the OpenGL backend at runtime)
# into one generated C++ file.
import os, sys, subprocess, argparse, re

def mangled(p):
    return re.sub(r'[^A-Za-z0-9]', '_', p)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--shader-dir', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--glslang', default='glslangValidator')
    args = ap.parse_args()

    d = args.shader_dir
    files = sorted(os.listdir(d))
    glsl_files = [f for f in files if f.endswith(('.vert', '.frag', '.comp', '.glsl'))]
    entry = [f for f in glsl_files if f.endswith(('.vert', '.frag', '.comp'))]

    spv = {}
    ok = True
    for f in entry:
        stage = 'vert' if f.endswith('.vert') else ('frag' if f.endswith('.frag') else 'comp')
        out_spv = os.path.join(os.path.dirname(args.out), f + '.spv')
        cmd = [args.glslang, '-V', '-S', stage, '--target-env', 'vulkan1.1',
               '-I' + d, '-o', out_spv, os.path.join(d, f)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print(r.stdout); print(r.stderr, file=sys.stderr)
            ok = False
        else:
            with open(out_spv, 'rb') as fh:
                spv[f] = fh.read()
    if not ok:
        sys.exit('shader compilation failed')

    lines = []
    lines.append('// AUTO-GENERATED by embed_shaders.py - do not edit')
    lines.append('#include "render/shader_embeds.hpp"')
    lines.append('#include <unordered_map>')
    lines.append('#include <string>')
    lines.append('namespace Genesis {')
    for f in glsl_files:
        with open(os.path.join(d, f), 'r', encoding='utf-8') as fh:
            src = fh.read()
        if ')"GLSL' in src:
            sys.exit('delimiter collision in ' + f)
        lines.append(f'static const char *GLSL_{mangled(f)} =')
        lines.append(f'R"GLSL({src})GLSL";')
    for f, blob in spv.items():
        n = len(blob) // 4
        u32 = [int.from_bytes(blob[i*4:i*4+4], 'little') for i in range(n)]
        lines.append(f'static const unsigned int SPV_{mangled(f)}[] = {{')
        for i in range(0, len(u32), 12):
            lines.append('  ' + ','.join(f'0x{x:08x}' for x in u32[i:i+12]) + ',')
        lines.append('};')
        lines.append(f'static const size_t SPV_{mangled(f)}_size = {len(blob)};')
    # accessors
    lines.append('const char *embeddedShaderGLSL(const std::string &name) {')
    for f in glsl_files:
        lines.append(f'  if (name == "{f}") return GLSL_{mangled(f)};')
    lines.append('  return nullptr; }')
    lines.append('const uint32_t *embeddedShaderSPV(const std::string &name, size_t &bytes) {')
    lines.append('  bytes = 0;')
    for f in spv:
        lines.append(f'  if (name == "{f}") {{ bytes = SPV_{mangled(f)}_size; return SPV_{mangled(f)}; }}')
    lines.append('  return nullptr; }')
    lines.append('} // namespace Genesis')

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(f'embedded {len(glsl_files)} glsl files, {len(spv)} SPIR-V modules')

if __name__ == '__main__':
    main()
